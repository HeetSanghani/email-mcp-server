def decode(b64_str):
    """Strip whitespace/newlines that may exist in the literal, then decode."""
    return base64.b64decode(b64_str.replace("\n", "").replace(" ", ""))


def write_file(path, data, executable=False):
    path = Path(path)
    path.write_bytes(data)
    if executable:
        try:
            os.chmod(path, 0o755)
        except Exception:
            pass
    return path


def file_summary(data):
    lines = data.decode("utf-8", errors="replace").count("\n")
    size  = len(data)
    return f"{lines} lines, {size:,} bytes"


def main():
    project = Path.cwd()

    print()
    print("=" * 60)
    print("  Email MCP Server — File Installer")
    print("=" * 60)
    print(f"  Installing into: {project}")
    print()

    # ── setup.py ──────────────────────────────────────────
    setup_data  = decode(SETUP_PY_B64)
    readme_data = decode(README_MD_B64)

    setup_path  = project / "setup.py"
    readme_path = project / "README.md"

    # Warn before overwriting
    for p, label in [(setup_path, "setup.py"), (readme_path, "README.md")]:
        if p.exists():
            try:
                ans = input(f"  {label} already exists. Overwrite? [Y/n]: ").strip().lower()
                if ans not in ("", "y", "yes"):
                    print(f"  Skipped {label}")
                    if label == "setup.py":
                        setup_data  = None
                    else:
                        readme_data = None
            except (KeyboardInterrupt, EOFError):
                print("\n  Cancelled.")
                sys.exit(0)

    created = []

    if setup_data is not None:
        write_file(setup_path, setup_data, executable=True)
        created.append(("setup.py",  file_summary(setup_data)))

    if readme_data is not None:
        write_file(readme_path, readme_data)
        created.append(("README.md", file_summary(readme_data)))

    if not created:
        print("  Nothing was created.")
        sys.exit(0)

    print()
    print("  Done! Files created:")
    print()
    for name, summary in created:
        print(f"    ✓  {name:<14} ({summary})")

